#!/usr/bin/env python3
"""Identify accompanying evidence bytes, independently of paper/results and Git."""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

from package_common import ROOT, canonical, sha256_file


def outputs(root: Path = ROOT) -> tuple[bytes, bytes]:
    files = [
        {"path": p.relative_to(root).as_posix(), "sha256": sha256_file(p)}
        for p in sorted((root / "evidence").rglob("*"), key=lambda p: p.relative_to(root).as_posix())
        if p.is_file() and not any(x in {"__pycache__", ".pytest_cache"} for x in p.parts)
    ]
    digest = hashlib.sha256(canonical(files)).hexdigest()
    value = {"algorithm": "sha256(canonical-json(sorted-path-and-sha256-list)); utf8; sorted-keys; compact-separators",
             "files": files, "sha256": digest, "scope": "evidence/** files only; runtime __pycache__ and .pytest_cache directories excluded",
             "schema": "fcig-cwc-evidence-identity-v1", "version": "3.2.0"}
    receipt = (json.dumps(value, indent=2, sort_keys=True) + "\n").encode("utf-8")
    tex = ("% Generated by scripts/build_evidence_identity.py.\n"
           + "\\newcommand{\\EvidenceDigest}{" + digest + "}\n").encode("ascii")
    return receipt, tex


def verify(root: Path = ROOT) -> bool:
    return all(p.is_file() and p.read_bytes() == data for p, data in zip(
        (root / "results/evidence_identity.json", root / "paper/evidence_identity.tex"), outputs(root)))


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    if args.check:
        passed = verify()
    else:
        for path, data in zip((ROOT / "results/evidence_identity.json", ROOT / "paper/evidence_identity.tex"), outputs()):
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
        passed = True
    print("PASS evidence identity" if passed else "FAIL evidence identity drift")
    return 0 if passed else 1


if __name__ == "__main__":
    raise SystemExit(main())
